//array
let arr = [1,2,3,4,5]

//adding
arr.push(6) //adds at last
console.log(arr)
arr.unshift(3) //adds at start
console.log(arr)

//removing
arr.pop(1) //from end.             //in removing we use indexes whereas while adding we use value
console.log(arr) 
arr.shift(1) //from start
console.log(arr)

//2d array
let arr1 = [[1,2],[3,4]]
arr.push([2,5])
